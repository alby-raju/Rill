import Foundation

public enum HARImportError: LocalizedError {
    case invalid, unsupported
    public var errorDescription: String? {
        switch self {
        case .invalid: "Expected a UTF-8 HAR 1.2 log with 1–1,000 request entries."
        case .unsupported:
            "This HAR request contains unsupported or ambiguous headers, body data or HTTP method."
        }
    }
}
/// Parses request data only. Response bodies, timings and executable extensions are never imported.
public enum HARImporter {
    public static func parse(_ input: Data) throws -> [CommandImport] {
        try WorkspaceFile.checkJSONBounds(input)
        let data = input.starts(with: [0xef, 0xbb, 0xbf]) ? Data(input.dropFirst(3)) : input
        guard String(data: data, encoding: .utf8) != nil,
            let root = try JSONSerialization.jsonObject(with: data) as? [String: Any],
            let log = root["log"] as? [String: Any], log["version"] as? String == "1.2",
            let entries = log["entries"] as? [[String: Any]], (1...1_000).contains(entries.count)
        else { throw HARImportError.invalid }
        return try entries.enumerated().map { index, entry in
            try Task.checkCancellation()
            guard let source = entry["request"] as? [String: Any],
                let methodText = source["method"] as? String,
                let method = HTTPMethod(rawValue: methodText),
                let address = source["url"] as? String
            else { throw HARImportError.unsupported }
            var request = RequestDraft()
            request.method = method
            request.url = address
            request.bodyMode = RequestBodyMode.none
            var warnings = [
                "Only the selected request is imported. Captured responses, timings, pages, connection metadata and extensions are omitted.",
                "URL query spelling is authoritative; HAR queryString metadata is not appended a second time. Rill transport defaults apply.",
            ]
            guard let headers = source["headers"] as? [[String: Any]], headers.count <= 10_000
            else { throw HARImportError.invalid }
            var omittedTransportHeaders = false
            for header in headers {
                guard let name = header["name"] as? String, let value = header["value"] as? String
                else { throw HARImportError.invalid }
                if ["host", "content-length", "connection", "transfer-encoding", "accept-encoding"]
                    .contains(name.lowercased()) || name.hasPrefix(":")
                {
                    omittedTransportHeaders = true
                    continue
                }
                try CommandImporter.header(name + ": " + value, into: &request)
            }
            if omittedTransportHeaders {
                warnings.append(
                    "Captured transport-managed headers are omitted and regenerated by Rill.")
            }
            if let cookies = source["cookies"] as? [Any], !cookies.isEmpty {
                warnings.append(
                    "Cookie objects are omitted. Only an explicit Cookie header is retained as plain text; review it before sending or sharing."
                )
            }
            if source["postData"] != nil && !(source["postData"] is [String: Any]) {
                throw HARImportError.invalid
            }
            if source["postData"] == nil, let size = source["bodySize"] as? NSNumber,
                size.intValue > 0
            {
                throw HARImportError.unsupported
            }
            if let body = source["postData"] as? [String: Any] {
                guard body["encoding"] == nil, body["_encoding"] == nil,
                    let mime = body["mimeType"] as? String, !mime.isEmpty,
                    !mime.unicodeScalars.contains(where: { $0.value < 32 || $0.value == 127 })
                else { throw HARImportError.unsupported }
                let media =
                    mime.split(separator: ";", maxSplits: 1).first?.trimmingCharacters(
                        in: .whitespaces
                    ).lowercased() ?? ""
                if let text = body["text"] as? String {
                    guard media != "multipart/form-data" else { throw HARImportError.unsupported }
                    request.bodyMode = .text
                    request.body = text
                    request.contentType = mime
                    warnings.append(
                        "Raw postData.text is authoritative; parameter metadata is not appended. Binary/encoded extensions are unsupported."
                    )
                } else if let params = body["params"] as? [[String: Any]],
                    media == "application/x-www-form-urlencoded"
                {
                    guard params.count <= 10_000 else { throw HARImportError.unsupported }
                    request.bodyMode = .form
                    request.formFields = try params.map { param in
                        guard param["fileName"] == nil, let name = param["name"] as? String,
                            let value = param["value"] as? String
                        else { throw HARImportError.unsupported }
                        return Field(name: name, value: value)
                    }
                    request.contentType = mime
                    warnings.append(
                        "Form parameters are re-encoded by Rill; original wire spelling is unavailable."
                    )
                } else {
                    throw HARImportError.unsupported
                }
                if let captured = request.headers.first(where: {
                    $0.name.lowercased() == "content-type"
                }), captured.value.caseInsensitiveCompare(mime) != .orderedSame {
                    throw HARImportError.unsupported
                }
            }
            var result = try CommandImporter.finalize(request, warnings: [])
            result.request.name = "HAR request \(index + 1) · \(method.rawValue)"
            result.warnings =
                Array(Set(warnings)).sorted()
                + result.warnings.filter { !$0.hasPrefix("Unspecified defaults") }
            result.warnings.append(
                "Recognized Basic/Bearer/API-key auth moves to Keychain on Apply. Other headers, URL and body values remain plain text and may contain secrets. No traffic or file reads occur."
            )
            return result
        }
    }
}
